def degrees(n,H):
    for h in range(1,H+1):
        for c in itertools.product(range(h+1),repeat=n):
            if sum(c)==h: yield c

def pbw(mu,order):
    # ordered monomials (weakly increasing in order index) of weight mu
    out=[]
    def rec(start,rem,cur):
        if all(x==0 for x in rem): out.append(tuple(cur)); return
        for k in range(start,len(order)):
            r=order[k]
            if all(r[i]<=rem[i] for i in range(len(rem))):
                rec(k,tuple(rem[i]-r[i] for i in range(len(rem))),cur+[r])
    rec(0,mu,[]); return out

def straighten(v,pos,br):
    def add(a,b): return tuple(x+y for x,y in zip(a,b))
    out={}; stack=list(v.items())
    while stack:
        w,c=stack.pop()
        if c==0: continue
        for i in range(len(w)-1):
            a,b=w[i],w[i+1]
            if pos[a]>pos[b]:
                stack.append((w[:i]+(b,a)+w[i+2:],c))
                if (a,b) in br:
                    stack.append((w[:i]+(add(a,b),)+w[i+2:],c*br[(a,b)]))
                break
        else:
            out[w]=out.get(w,0)+c
    return {k:c for k,c in out.items() if c}

