"""Core: 0-Hecke H_N(0) right action on V^{(x)N}, V=C^n (Jung-Oh (4.5) / KT NCSF V q=0 limit),
U_0(gl_n) action (Jung-Oh Def 4.2 coproduct), commutants, radicals. Exact arithmetic via python-flint."""
import itertools, flint
from flint import fmpz_mat, fmpq_mat, fmpq

def words(n, N):
    return list(itertools.product(range(n), repeat=N))

def setup(n, N):
    W = words(n, N); idx = {w: k for k, w in enumerate(W)}; d = len(W)
    return W, idx, d

def T_ops(n, N):
    """Matrices of v -> v.pi_i (column convention: M[:,col(w)] = image of w)."""
    W, idx, d = setup(n, N)
    Ts = []
    for i in range(N - 1):
        M = [[0]*d for _ in range(d)]
        for w in W:
            a, b = w[i], w[i+1]
            if a < b:
                u = list(w); u[i], u[i+1] = b, a; M[idx[tuple(u)]][idx[w]] = 1
            elif a > b:
                M[idx[w]][idx[w]] = -1
        Ts.append(fmpz_mat(M))
    return Ts

def U0_ops(n, N):
    """e_i = sum_p 1..1 (x) E_{i,i+1}@p (x) k_i...k_i ; f_i = sum_p k_{i+1}..k_{i+1} (x) E_{i+1,i}@p (x) 1..1;
    k_i = (sum_{j!=i} E_jj)^{(x)N}.  (Jung-Oh Def 4.2 + rho_V)"""
    W, idx, d = setup(n, N)
    ops = {}
    for i in range(n - 1):
        E = [[0]*d for _ in range(d)]; F = [[0]*d for _ in range(d)]
        for w in W:
            for p in range(N):
                if w[p] == i+1 and all(x != i for x in w[p+1:]):   # e_i : i+1 -> i, later factors k_i (no letter i)
                    u = list(w); u[p] = i; E[idx[tuple(u)]][idx[w]] += 1
                if w[p] == i and all(x != i+1 for x in w[:p]):     # f_i : i -> i+1, earlier factors k_{i+1}
                    u = list(w); u[p] = i+1; F[idx[tuple(u)]][idx[w]] += 1
        ops['e%d' % i] = fmpz_mat(E); ops['f%d' % i] = fmpz_mat(F)
    for i in range(n):
        K = [[0]*d for _ in range(d)]
        for w in W:
            if i not in w: K[idx[w]][idx[w]] = 1
        ops['k%d' % i] = fmpz_mat(K)
    return ops

def flat(M):
    return [int(M[r, c]) for r in range(M.nrows()) for c in range(M.ncols())]

def rank_rows(rows, ncols):
    if not rows: return 0
    return fmpz_mat(rows).rank()

def algebra_span(gens, d):
    """Basis (list of matrices) of unital algebra generated by gens, by closure."""
    I = fmpz_mat([[int(r == c) for c in range(d)] for r in range(d)])
    basis = [I]; rows = [flat(I)]; frontier = [I]
    while frontier:
        new = []
        for X in frontier:
            for g in gens:
                Y = g * X
                cand = rows + [flat(Y)]
                if fmpz_mat(cand).rank() > len(rows):
                    rows.append(flat(Y)); basis.append(Y); new.append(Y)
        frontier = new
    return basis

def nullspace_int(rows, ncols):
    """Integer basis of right nullspace of integer matrix (list of rows)."""
    if not rows:
        return [[int(i == j) for j in range(ncols)] for i in range(ncols)]
    A = fmpz_mat(rows)
    X, nullity = A.nullspace()
    return [[int(X[r, c]) for r in range(ncols)] for c in range(nullity)]
