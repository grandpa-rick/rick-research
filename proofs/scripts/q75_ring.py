#!/usr/bin/env python3
"""Q75 ring structure: G = Sym/Ann(R) under skewing, R = ribbon r_(2^k) (and controls).

Power-sum basis, exact rationals (sympy).  p_n^perp = n d/dp_n.
x -> p_1, y -> p_2 (deg 1, 2).  I = ker(Q[x,y] -> G).
Compare with H_k = Q[e1,e2]/(h_{k+1},h_{k+2}) via graded automorphisms
x -> a x, y -> b y + c x^2  (torus-normalised a = 1).
Grade of everything here: computed.
"""
import sys, time, itertools
from functools import reduce
import sympy as sp
from sympy.utilities.iterables import partitions as sp_partitions

T0 = time.time()

def partitions(n):
    out = []
    for p in sp_partitions(n):
        lam = []
        for part, m in sorted(p.items(), reverse=True):
            lam += [part] * m
        out.append(tuple(lam))
    return out

def zee(lam):
    from collections import Counter
    z = 1
    for part, m in Counter(lam).items():
        z *= part ** m * sp.factorial(m)
    return z

def compositions(n):
    if n == 0:
        yield ()
        return
    for first in range(1, n + 1):
        for rest in compositions(n - first):
            yield (first,) + rest

class Ring:
    def __init__(self, d):
        self.d = d
        self.P = sp.symbols('p1:%d' % (d + 1))
        self._h = {0: sp.Integer(1)}

    def p(self, lam):
        return reduce(lambda a, b: a * b, [self.P[i - 1] for i in lam], sp.Integer(1))

    def h(self, n):
        if n < 0:
            return sp.Integer(0)
        if n not in self._h:
            self._h[n] = sp.expand(sum(self.p(l) / zee(l) for l in partitions(n)))
        return self._h[n]

    def hprod(self, beta):
        return sp.expand(reduce(lambda a, b: a * b, [self.h(b) for b in beta], sp.Integer(1)))

    def ribbon(self, alpha):
        """R_alpha = sum over coarsenings beta of (-1)^{l(alpha)-l(beta)} h_beta."""
        L = len(alpha)
        tot = sp.Integer(0)
        for cuts in itertools.product([0, 1], repeat=L - 1):
            beta, cur = [], alpha[0]
            for j, c in enumerate(cuts):
                if c:  # merge
                    cur += alpha[j + 1]
                else:
                    beta.append(cur); cur = alpha[j + 1]
            beta.append(cur)
            tot += (-1) ** (L - len(beta)) * self.hprod(beta)
        return sp.expand(tot)

    def schur(self, lam):
        n = len(lam)
        M = sp.Matrix(n, n, lambda i, j: self.h(lam[i] - i + j))
        return sp.expand(M.det())

    def skew_by_p(self, lam, F):
        for part in lam:
            F = part * sp.diff(F, self.P[part - 1])
        return sp.expand(F)

    def skew_poly(self, phi, F):
        """phi a polynomial in self.P (power sums); returns phi^perp F."""
        phi = sp.Poly(sp.expand(phi), *self.P)
        tot = sp.Integer(0)
        for mon, co in phi.terms():
            lam = []
            for i, e in enumerate(mon):
                lam += [i + 1] * e
            tot += co * self.skew_by_p(lam, F)
        return sp.expand(tot)

def coeff_matrix(polys, gens):
    """rows = polys, columns = monomials."""
    dicts = [sp.Poly(f, *gens).as_dict() if f != 0 else {} for f in polys]
    mons = sorted(set().union(*[set(d) for d in dicts])) if dicts else []
    return sp.Matrix(len(polys), max(len(mons), 1),
                     lambda i, j: dicts[i].get(mons[j], 0) if mons else 0)

x, y = sp.symbols('x y')
X, Y = sp.symbols('X Y')

def xy_monos(n):
    return [x ** (n - 2 * b) * y ** b for b in range(n // 2 + 1)]

def analyse(Rg, R, label):
    d = Rg.d
    P = Rg.P
    print('=' * 70)
    print(label, ' degree', d)
    # 1. Hilbert function via all p_lambda
    hilb, hilb_xy = [], []
    for i in range(d + 1):
        imgs = [Rg.skew_by_p(l, R) for l in partitions(i)]
        r = coeff_matrix(imgs, P).rank() if any(f != 0 for f in imgs) else 0
        hilb.append(r)
        imgs2 = [Rg.skew_by_p([1] * (i - 2 * b) + [2] * b, R) for b in range(i // 2 + 1)]
        r2 = coeff_matrix(imgs2, P).rank() if any(f != 0 for f in imgs2) else 0
        hilb_xy.append(r2)
    print('Hilb(G)          =', hilb)
    print('Hilb(<p1,p2>)    =', hilb_xy, ' generated by p1,p2:', hilb == hilb_xy)
    # derived formula p_{2n} = -(-p2)^n, p_{2n+1} = p1(-p2)^n in G
    ok_der = True
    for n in range(3, d + 1):
        m = n // 2
        form = -(-P[1]) ** m if n % 2 == 0 else P[0] * (-P[1]) ** m
        # in G means (p_n - form) * g kills R for all g: test g = all p_mu of deg <= d-n
        for j in range(0, d - n + 1):
            for mu in partitions(j):
                if Rg.skew_poly((P[n - 1] - form) * Rg.p(mu), R) != 0:
                    ok_der = False
    print('derived formula p_n = p1^{n mod 2}(-1)^{..}(-p2)^{n//2} holds in G:', ok_der)
    # 2. ideal I in Q[x,y]
    Ibasis = {}
    for n in range(0, d + 3):
        mons = xy_monos(n)
        imgs = [Rg.skew_poly(mo.subs({x: P[0], y: P[1]}), R) for mo in mons]
        if all(f == 0 for f in imgs):
            ker = [sp.Matrix.eye(len(mons))[:, j] for j in range(len(mons))]
        else:
            M = coeff_matrix(imgs, P).T  # columns = monomials
            ker = M.nullspace()
        Ibasis[n] = [sp.expand(sum(v[j] * mons[j] for j in range(len(mons)))) for v in ker]
    gens = []
    for n in range(0, d + 3):
        prev = [sp.expand(x * g) for g in Ibasis.get(n - 1, [])] + \
               [sp.expand(y * g) for g in Ibasis.get(n - 2, [])]
        mons = xy_monos(n)
        def rk(L):
            L = [f for f in L if f != 0]
            if not L:
                return 0
            return sp.Matrix([[sp.Poly(f, x, y).coeff_monomial(mo) for mo in mons] for f in L]).rank()
        rprev = rk(prev)
        need = len(Ibasis[n]) - rprev
        chosen = list(prev)
        for g in Ibasis[n]:
            if need == 0:
                break
            if rk(chosen + [g]) > rk(chosen):
                chosen.append(g); need -= 1
                # normalise
                lc = sp.Poly(g, x, y).coeffs()[0]
                gens.append((n, sp.expand(g / lc)))
    print('minimal generators of I:')
    for n, g in gens:
        print('   deg', n, ':', g)
    # 4. dual generator: F = R restricted to p_{>=3}=0, x -> d/dX, y -> 2 d/dY
    F = sp.expand(R.subs({P[j]: 0 for j in range(2, d)}).subs({P[0]: X, P[1]: Y}))
    print('F_G (R at p_{>=3}=0; X=p1,Y=p2; x acts d/dX, y acts 2d/dY) =', F)
    # check Ann(F) = I up to degree d+2
    okF = True
    for n in range(0, d + 3):
        mons = xy_monos(n)
        imgs = [sp.expand(sp.diff(F, X, n - 2 * b, Y, b) * 2 ** b) if True else 0 for b in range(n // 2 + 1)]
        imgs = []
        for b in range(n // 2 + 1):
            f = F
            if n - 2 * b: f = sp.diff(f, X, n - 2 * b)
            if b: f = sp.diff(f, Y, b) * 2 ** b
            imgs.append(sp.expand(f))
        if all(f == 0 for f in imgs):
            kd = len(mons)
        else:
            kd = len(mons) - coeff_matrix(imgs, (X, Y)).rank()
        if kd != len(Ibasis[n]):
            okF = False
    print('Ann_{Q[x,y]}(F_G) has same graded dims as I (so I = Ann(F_G) since I subset Ann(F_G)):', okF)
    return hilb, gens, F

def H_ideal(k):
    # h_m in e1,e2 : sum h_m t^m = 1/(1 - e1 t + e2 t^2), with e1 -> x, e2 -> y
    hs = [sp.Integer(1), x]
    for m in range(2, k + 3):
        hs.append(sp.expand(x * hs[-1] - y * hs[-2]))
    return hs[k + 1], hs[k + 2]

def dual_H(k):
    """Macaulay dual (differentiation, e1 -> d/dE1, e2 -> d/dE2) of H_k in degree 2k."""
    E1, E2 = sp.symbols('E1 E2')
    mons = [E1 ** (2 * k - 2 * b) * E2 ** b for b in range(k + 1)]
    cs = sp.symbols('c0:%d' % (k + 1))
    F = sum(c * m for c, m in zip(cs, mons))
    g1, g2 = H_ideal(k)
    eqs = []
    for g in (g1, g2):
        for mult in xy_monos(2 * k - sp.Poly(g, x, y).total_degree() if False else 0):
            pass
    # apply every multiple of g1,g2 landing in degree 2k
    deg1, deg2 = k + 1, k + 2
    ops = [sp.expand(m * g1) for m in xy_monos(2 * k - deg1)] + [sp.expand(m * g2) for m in xy_monos(2 * k - deg2)]
    for op in ops:
        val = sp.Integer(0)
        for (a, b), co in sp.Poly(op, x, y).as_dict().items():
            t = F
            if a: t = sp.diff(t, E1, a)
            if b: t = sp.diff(t, E2, b)
            val += co * t
        eqs.append(sp.expand(val))
    sol = sp.solve(eqs, cs, dict=True)[0]
    Fs = sp.expand(F.subs(sol))
    free = [c for c in cs if Fs.has(c)]
    Fs = sp.expand(Fs.subs({free[0]: 1}))
    return Fs

def iso_test(gens, k, label):
    """Find (a=1,b,c) with sigma(I) = J = (h_{k+1}, h_{k+2}), sigma: x->x, y->b y + c x^2."""
    g1h, g2h = H_ideal(k)
    degs = sorted(n for n, _ in gens)
    if degs != [k + 1, k + 2]:
        print('  [%s] generator degrees %s != [k+1,k+2]: NOT isomorphic (embedding/CI type differs)' % (label, degs))
        return None
    g1 = [g for n, g in gens if n == k + 1][0]
    g2 = [g for n, g in gens if n == k + 2][0]
    b, c, lam, mu, nu = sp.symbols('b c lam mu nu')
    sig = lambda f: sp.expand(f.subs({y: b * y + c * x ** 2}, simultaneous=True))
    e1 = sp.Poly(sig(g1) - lam * g1h, x, y).coeffs()
    e2 = sp.Poly(sig(g2) - mu * g2h - nu * x * g1h, x, y).coeffs()
    sols = sp.solve(e1 + e2, [b, c, lam, mu, nu], dict=True)
    sols = [s for s in sols if s.get(b, b) != 0 and s.get(lam, 1) != 0]
    print('  [%s] solutions (a=1, torus-normalised) over C:' % label, sols)
    rat = [s for s in sols if all(v.is_rational for v in s.values())]
    print('  [%s] iso over C: %s ; iso over Q: %s' % (label, bool(sols), bool(rat)))
    return sols

def main():
    kmax = int(sys.argv[1]) if len(sys.argv) > 1 else 5
    for k in range(2, kmax + 1):
        t = time.time()
        d = 2 * k
        Rg = Ring(d)
        R = Rg.ribbon(tuple([2] * k))
        hilb, gens, F = analyse(Rg, R, 'ribbon r_(2^%d)' % k)
        q = sp.Symbol('q')
        qb = sp.Poly(sp.cancel((1 - q ** (k + 1)) * (1 - q ** (k + 2)) / ((1 - q) * (1 - q ** 2))), q).all_coeffs()[::-1]
        print('[k+2 choose 2]_q =', qb, ' match:', [int(v) for v in qb] == hilb)
        g1h, g2h = H_ideal(k)
        print('H_k: h_%d =' % (k + 1), g1h, ';  h_%d =' % (k + 2), g2h)
        print('F_H (dual of H_k, E1,E2 plain derivatives) =', dual_H(k))
        iso_test(gens, k, 'ribbon k=%d' % k)
        # control: rectangle
        Rs = Rg.schur((k, k))
        _, gs, _ = analyse(Rg, Rs, 'Schur s_(%d,%d) control' % (k, k))
        iso_test(gs, k, 'rectangle k=%d' % k)
        print('time k=%d: %.1fs' % (k, time.time() - t))
    # negative controls (degree 4 so the target is Gr(2,4), k=2)
    Rg = Ring(4)
    for alpha in [(1, 3), (3, 1), (1, 1, 2), (2, 1, 1), (1, 2, 1)]:
        _, gs, _ = analyse(Rg, Rg.ribbon(alpha), 'ribbon %s control' % (alpha,))
        iso_test(gs, 2, 'ribbon %s' % (alpha,))
    for lam in [(3, 1), (2, 1, 1)]:
        _, gs, _ = analyse(Rg, Rg.schur(lam), 'Schur %s control' % (lam,))
        iso_test(gs, 2, 'schur %s' % (lam,))
    # synthetic degree-4 Gorenstein with Hilb 1,1,2,1,1 but different Q-square class:
    # R = p1^4/24 + p2^2/8 * t  for a few t (as Sym elements) -- shows Q vs C split
    for tt in [1, 2, 3]:
        Rsyn = sp.expand(Rg.P[0] ** 4 + tt * Rg.P[1] ** 2)
        _, gs, _ = analyse(Rg, Rsyn, 'synthetic p1^4 + %d p2^2' % tt)
        iso_test(gs, 2, 'synthetic t=%d' % tt)
    print('total runtime %.1fs' % (time.time() - T0))

if __name__ == '__main__':
    main()
