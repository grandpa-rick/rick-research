# Ind_{H_c x H_d}^{H_N}(C_D1 [x] C_D2) for H_N(0), pi-convention (pi_i^2=pi_i).
# Basis: minimal left coset reps w in W^K (w increasing on each block of positions).
# pi_i T_w = T_{s_i w} if ascent & s_i w in W^K; = chi(p) T_w if s_i w = w s_p (p in K); = T_w if left descent.
import itertools, sympy as sp, sys, json
from fractions import Fraction

def minreps(N, blocks):
    reps=[]
    for w in itertools.permutations(range(1,N+1)):
        ok=True; pos=0
        for b in blocks:
            seg=w[pos:pos+b]
            if any(seg[i]>seg[i+1] for i in range(b-1)): ok=False;break
            pos+=b
        if ok: reps.append(w)
    return reps

def ind_module(blocks, D):  # D: set of positions p (1-based, within-block adjacencies) where pi_p acts by 1
    N=sum(blocks); reps=minreps(N,blocks); idx={w:k for k,w in enumerate(reps)}
    bstart=set(); pos=0
    for b in blocks: pos+=b; bstart.add(pos)  # p in bstart => p,p+1 in different blocks
    n=len(reps); mats={}
    for i in range(1,N):
        M=sp.zeros(n,n)
        for w,k in idx.items():
            inv={v:p for p,v in enumerate(w,1)}
            a,b=inv[i],inv[i+1]
            if a>b: M[k,k]=1
            elif b==a+1 and a not in bstart:
                M[k,k]=1 if a in D else 0
            else:
                u=tuple(i+1 if v==i else i if v==i+1 else v for v in w); M[idx[u],k]=1
        mats[i]=M
    return reps,mats

def check_rel(mats,N):
    for i in mats:
        assert mats[i]**2==mats[i]
        if i+1 in mats: assert mats[i]*mats[i+1]*mats[i]==mats[i+1]*mats[i]*mats[i+1]
        for j in mats:
            if j>i+1: assert mats[i]*mats[j]==mats[j]*mats[i]

def endo(mats,n):
    # X with XA=AX for all generators
    syms=sp.symbols('x0:%d'%(n*n)); X=sp.Matrix(n,n,syms)
    eqs=[]
    for A in mats.values():
        eqs+=list(X*A-A*X)
    Msys=sp.Matrix([[sp.diff(e,s) for s in syms] for e in eqs if e!=0]) if eqs else sp.zeros(0,n*n)
    ns=Msys.nullspace()
    return [sp.Matrix(n,n,list(v)) for v in ns]

def n_summands(E,n,seed=1):
    import random; random.seed(seed)
    phi=sum((random.randint(-50,50)*B for B in E), sp.zeros(n,n))
    t=sp.symbols('t'); cp=sp.Poly(phi.charpoly(t).as_expr(),t)
    sq=sp.Poly(sp.quo(cp.as_expr(), sp.gcd(cp.as_expr(), sp.diff(cp.as_expr(),t))),t)
    return sq.degree(), phi

def wlong_parab(S,N):
    # reduced word of longest element of parabolic generated by S
    w=[]; S=sorted(S); runs=[]
    for s in S:
        if runs and s==runs[-1][-1]+1: runs[-1].append(s)
        else: runs.append([s])
    for r in runs:
        a,b=r[0],r[-1]+1  # S_{[a,b]}
        for top in range(b-1,a-1,-1):
            w+=list(range(a,top+1))
    return w

def character(mats,N,n):
    # multiplicity of C_K (K = set where pi acts by 1) via traces of pi_{w0(S)} + Mobius
    tr={}
    for r in range(N):
        for S in itertools.combinations(range(1,N),r):
            P=sp.eye(n)
            for i in wlong_parab(S,N): P=mats[i]*P
            tr[S]=P.trace()
    mult={}
    for r in range(N):
        for K in itertools.combinations(range(1,N),r):
            # tr[S] = sum_{K>=S} m_K  => m_K = sum_{S>=K} (-1)^{|S-K|} tr[S]
            m=0
            for S in tr:
                if set(K)<=set(S): m+=(-1)**(len(S)-len(K))*tr[S]
            if m: mult[K]=m
    return mult
